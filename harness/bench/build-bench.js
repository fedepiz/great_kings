#!/usr/bin/env node
// =====================================================================
// build-bench.js — assemble orders-bench.jsx from source, never by hand
// =====================================================================
// The bench used to carry a PACK baked into it: 264KB of data that went stale the moment
// the rules changed, and had to be re-injected and re-uploaded for every experiment.
//
// It now carries the ENGINE and the GENERATOR instead, so it can make a corpus itself from
// any seed. That is smaller than the pack it replaces, and it cannot go stale: the corpus is
// generated by the same code the game runs.
//
// NOTHING HERE IS HAND-MAINTAINED. The engine core, the corpus generator and the pack
// renderer are lifted from their real files at build time, so a fix to any of them reaches
// the bench on the next build and nowhere else.
// =====================================================================
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const read = (p) => fs.readFileSync(p, "utf8");

// ---- 1. the engine: read whole, not sliced ----
let core = read(path.join(ROOT, "levant", "engine.js"));
core = core.slice(0, core.lastIndexOf("\nexport {"));   // in one file everything is in scope

// ---- 2. the corpus generator: its body, without the file-writing CLI ----
let gen = read(path.join(__dirname, "gen-corpus.js"));
gen = gen.slice(gen.indexOf("const clone ="));                       // drop the require header
gen = gen.slice(0, gen.indexOf("// ---- the command line"));          // drop the CLI
gen = gen.replace(/\bM\./g, "");                                      // everything is in scope here
// the generator pulls a few engine names into locals; in one file they are already here
gen = gen.replace(/^const R = R, BT = BT, PNAME = PNAME, GOODS = GOODS;$/m, "");
// `const BACKTRACK = ORDER_NEVER, key = cmdKey;` survives the M.-stripping as a plain alias
// of two engine names, and the pack renderer below relies on it being in scope. Leave it.
gen = gen.replace(/^const clone = .*$/m, "const cloneG = (g) => JSON.parse(JSON.stringify(g));");
gen = gen.replace(/\bclone\(/g, "cloneG(");

// ---- 3. the pack renderer: same treatment ----
let ren = read(path.join(__dirname, "render-pack.js"));
ren = ren.slice(ren.indexOf("function applyFixtures"));
ren = ren.slice(0, ren.indexOf("// ---- the command line"));
ren = ren.replace(/\bM\./g, "");
ren = ren.replace(/^const clone = .*$/m, "");
ren = ren.replace(/\bclone\(/g, "cloneG(");
ren = ren.replace(/\bbare\(/g, "bareCmd(");
// the renderer's own helpers live above the slice point; everything else it needs
// (BACKTRACK, key, cloneG) is already in scope from the generator
ren = "const bareCmd = (c) => { const o = { ...c }; delete o.standing; delete o.b; return o; };\n" + ren;

// ---- 4. the bench component ----
const bench = read(path.join(__dirname, "orders-bench.jsx"));

const out = `import React, { useState, useMemo, useRef } from "react";

// =====================================================================
//  ORDERS BENCH — built by harness/bench/build-bench.js. Do not edit.
//  Sources: levant/engine.js · harness/bench/gen-corpus.js, render-pack.js, orders-bench.jsx
//  Built:   ${new Date().toISOString()}
// =====================================================================

// ============================ ENGINE ============================
${core}

// ====================== CORPUS GENERATOR ========================
${gen}

// ======================== PACK RENDERER =========================
${ren}

// ========================== THE BENCH ===========================
${bench.replace(/^import React[^\n]*\n/, "")}
`;

// WHERE THE ARTIFACT LANDS. This used to default to /mnt/user-data/outputs/ — the sandbox
// this project was written in, which exists nowhere else, so `./harness/inject.sh` failed
// outright on a clone. The default is now inside the repo; GREAT_KINGS_PUBLISH_BENCH points
// it at wherever you upload from, and an explicit argument still wins over both.
const dest = process.argv[2] || process.env.GREAT_KINGS_PUBLISH_BENCH
  || path.join(ROOT, "dist", "orders-bench.jsx");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log("built", dest, (fs.statSync(dest).size / 1024).toFixed(0) + "KB");
console.log("  engine core   :", (core.length / 1024).toFixed(0) + "KB");
console.log("  generator     :", (gen.length / 1024).toFixed(0) + "KB");
console.log("  pack renderer :", (ren.length / 1024).toFixed(0) + "KB");
console.log("  bench UI      :", (bench.length / 1024).toFixed(0) + "KB");
